"""GPL-3.0. Mechanical async adaptation of the existing scanner, not new OCR logic.

Only the native-process OCR bridge and Node catalog bootstrap are replaced.
Propagate await through the existing call graph so Tesseract.js can run in its
own worker without SharedArrayBuffer, cross-origin isolation or blocking the UI.
"""
import ast
from pathlib import Path

FILES = {'card.py':'vendor/card.py', 'scanner.py':'scanner.py',
         'data.py':'vendor/data.py', 'icon_recognition.py':'icon_recognition.py',
         'image_integrity.py':'vendor/image_integrity.py', 'test_scanner.py':'test_scanner.py'}

def adapt(root, catalog):
    sources = {name:(root/path).read_text() for name,path in FILES.items()}
    sources['data.py'] = sources['data.py'].replace('HERE = Path', '''from types import SimpleNamespace
_feature_path = Path('/scanner/features.npz')
_feature_cache = np.load(_feature_path, allow_pickle=False) if _feature_path.exists() else None
_feature_groups = {}
def cached_asset_features(prefix):
    if _feature_cache is None: return None
    if prefix in _feature_groups: return _feature_groups[prefix]
    result = {}
    for key in _feature_cache.files:
        if key.startswith(prefix+'::') and key.endswith('::descriptors'):
            identity=key[len(prefix)+2:-len('::descriptors')]
            points=_feature_cache[prefix+'::'+identity+'::points']
            descriptors=_feature_cache[key]
            if descriptors.ndim!=2 or descriptors.shape!=(len(points),128) or not np.isfinite(descriptors).all():
                raise RuntimeError('Invalid prepared SIFT features')
            result[identity]=([SimpleNamespace(pt=tuple(point)) for point in points],descriptors)
    _feature_groups[prefix] = result
    return result
HERE = Path''')
    sources['data.py'] = sources['data.py'].replace('kp,des=SIFT.detectAndCompute(img,None)', '''cached=cached_asset_features(id_key)
        kp,des=cached[r[id_key]] if cached is not None else SIFT.detectAndCompute(img,None)''')
    sources['card.py'] = 'from data import cached_asset_features\n'+sources['card.py']
    sources['card.py'] = sources['card.py'].replace('def _load_asset_features(folder: str, max_side: int) -> dict:', '''def _load_asset_features(folder: str, max_side: int) -> dict:
    cached=cached_asset_features(folder)
    if cached is not None: return cached''')
    sources['data.py'] = sources['data.py'].replace(
        "CATALOG = json.loads(subprocess.check_output(\n    ['node', '--experimental-strip-types', str(HERE.parent / 'canonical.mjs')], text=True))",
        "CATALOG = json.loads(Path('/scanner/catalog.json').read_text())")
    trees = {name:ast.parse(source) for name,source in sources.items()}
    # Keep the same preprocessing/config and one text result per image.
    for node in trees['card.py'].body:
        if isinstance(node,ast.FunctionDef) and node.name=='tess_batch':
            node.body=ast.parse('return [pytesseract.image_to_string(image, config=config) for image in images]').body
    def called(node):
        return node.func.id if isinstance(node.func,ast.Name) else node.func.attr if isinstance(node.func,ast.Attribute) else None
    async_names={'image_to_string','tess_batch'}
    while True:
        added={node.name for tree in trees.values() for node in ast.walk(tree)
               if isinstance(node,ast.FunctionDef) and any(isinstance(call,ast.Call) and called(call) in async_names for call in ast.walk(node))}
        if added<=async_names: break
        async_names|=added
    class AwaitCalls(ast.NodeTransformer):
        def visit_Call(self,node):
            self.generic_visit(node)
            return ast.copy_location(ast.Await(value=node),node) if called(node) in async_names else node
        def visit_FunctionDef(self,node):
            self.generic_visit(node)
            if node.name in async_names:
                return ast.copy_location(ast.AsyncFunctionDef(name=node.name,args=node.args,body=node.body,decorator_list=node.decorator_list,returns=node.returns,type_comment=node.type_comment,type_params=[]),node)
            return node
    result={}
    for name,tree in trees.items():
        tree=ast.fix_missing_locations(AwaitCalls().visit(tree));compile(tree,name,'exec')
        result[name]='# GPL-3.0; generated by browser/async_sources.py from retained scanner source.\n'+ast.unparse(tree)+'\n'
    result['pytesseract.py']='''import cv2
from js import scannerOCR
async def image_to_string(image, config=''):
    success, png = cv2.imencode('.png', image)
    if not success: raise ValueError('OCR crop could not be encoded')
    return await scannerOCR(png.tobytes(), config)
'''
    return result
