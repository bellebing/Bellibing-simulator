import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const portraits = read('../../ui-prototypes/assets/characters/portraits/manifest.json');
const heroes = read('../../ui-prototypes/assets/characters/hero-art/runtime-data.json');
const stats = read('../../ui-prototypes/assets/build-stats/runtime-data.json');
const metadata = new Map(stats.characters.map(row => [row.id, row]));
const heroById = new Map(heroes.characters.map(row => [row.characterId, row]));
const rows = [
  ...portraits.portraits.filter(row => row.releaseStatus === 'RELEASED' && row.uiEligible),
  ...portraits.roverPortraits.map(row => ({ ...row, characterName: `Rover (${row.characterId.slice(6).replace(/^./, c => c.toUpperCase())})` })),
].map(row => {
  const hero = heroById.get(row.characterId);
  const face = row.targetPath.replace('docs/', '../../');
  return {
    id: row.characterId,
    name: row.characterName,
    element: metadata.get(row.characterId)?.element ?? null,
    face,
    art: hero?.status === 'READY' ? hero.assetPath.replace('assets/', '../../ui-prototypes/assets/') : face,
    artStatus: hero?.status === 'READY' ? 'HERO' : 'PORTRAIT_FALLBACK',
  };
}).sort((a, b) => a.name.localeCompare(b.name, 'en'));
if (rows.length !== 59) throw new Error(`Expected 59 released Characters; found ${rows.length}`);
const output = '// Generated by ../tools/export-catalog.mjs from existing reviewed presentation manifests.\n' +
  '// Identity/art only. No recommendations, saved account data or gameplay calculations.\n' +
  `export const CHARACTER_CATALOG = ${JSON.stringify(rows, null, 2)};\n`;
const destination = fileURLToPath(new URL('../v1.1/modules/catalog.js', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('UI Lab catalog is stale');
  console.log(`UI Lab catalog parity passed (${rows.length} Characters).`);
} else writeFileSync(destination, output);
