import { CHARACTER_CATALOG as CANONICAL_CHARACTERS } from '../../../src/data/characters.ts';
import { WEAPON_CATALOG as CANONICAL_WEAPONS } from '../../../src/data/weapons.ts';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const portraits = read('../../ui-prototypes/assets/characters/portraits/manifest.json');
const heroes = read('../../ui-prototypes/assets/characters/hero-art/runtime-data.json');
const stats = read('../../ui-prototypes/assets/build-stats/runtime-data.json');
const metadata = new Map(stats.characters.map(row => [row.id, row]));
const canonicalById = new Map(CANONICAL_CHARACTERS.map(person => [person.id, person]));
const sequences = new Map(read('../../ui-prototypes/assets/sequence-runtime.json').characters.map(person => [person.characterId, person]));
const skills = new Map(read('../../ui-prototypes/assets/skills-runtime.json').characters.map(person => [person.characterId, person]));
const weaponArt = new Map(read('../../ui-prototypes/assets/weapons/manifest.json').icons.map(weapon => [weapon.weaponId, weapon]));
const presentationPath = path => path?.replace('assets/', '../../ui-prototypes/assets/') ?? null;
const heroById = new Map(heroes.characters.map(row => [row.characterId, row]));
const rows = [
  ...portraits.portraits.filter(row => row.releaseStatus === 'RELEASED' && row.uiEligible),
  ...portraits.roverPortraits.map(row => ({ ...row, characterName: `Rover (${row.characterId.slice(6).replace(/^./, c => c.toUpperCase())})` })),
].map(row => {
  const hero = heroById.get(row.characterId);
  const face = row.targetPath.replace('docs/', '../../');
  return {
    id: row.characterId,
    name: row.characterName,
    element: metadata.get(row.characterId)?.element ?? null,
    rarity: [4, 5].includes(canonicalById.get(row.characterId)?.rarity) ? canonicalById.get(row.characterId).rarity : null,
    weaponType: canonicalById.get(row.characterId)?.weaponType ?? null,
    sequences: (sequences.get(row.characterId)?.chains ?? []).map(chain => ({ sequence: chain.sequence, name: chain.name, art: presentationPath(chain.assetPath) })),
    forte: skills.get(row.characterId)?.status === 'SOURCE_BACKED' ? { nodes: skills.get(row.characterId).nodes.map(node => ({ id: node.id, parents: node.parents, kind: node.kind, role: node.role, name: node.name, art: presentationPath(node.assetPath), column: node.column, row: node.row })) } : null,
    face,
    art: hero?.status === 'READY' ? hero.assetPath.replace('assets/', '../../ui-prototypes/assets/') : face,
    artStatus: hero?.status === 'READY' ? 'HERO' : 'PORTRAIT_FALLBACK',
  };
}).sort((a, b) => a.name.localeCompare(b.name, 'en'));
if (rows.length !== 59) throw new Error(`Expected 59 released Characters; found ${rows.length}`);
const weapons = CANONICAL_WEAPONS.filter(weapon => weapon.releaseStatus === 'RELEASED').map(weapon => ({ id: weapon.id, name: weapon.name, rarity: [1,2,3,4,5].includes(weapon.rarity) ? weapon.rarity : null, art: weaponArt.get(weapon.id)?.targetPath.replace('docs/', '../../') ?? null }));
const output = '// Generated by ../tools/export-catalog.mjs from existing reviewed presentation manifests.\n' +
  '// Canonical identity/rarity and read-only presentation assets only. No recommendations, saved account data or gameplay calculations.\n' +
  `export const CHARACTER_CATALOG = ${JSON.stringify(rows, null, 2)};\nexport const WEAPON_CATALOG = ${JSON.stringify(weapons, null, 2)};\n`;
const destination = fileURLToPath(new URL('../v1.1/modules/catalog.js', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('UI Lab catalog is stale');
  console.log(`UI Lab catalog parity passed (${rows.length} Characters / ${weapons.length} Weapons).`);
} else writeFileSync(destination, output);
