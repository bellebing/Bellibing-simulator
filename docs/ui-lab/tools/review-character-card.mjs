import {chooseIllustrativeResult} from './review-fixtures.mjs';
import assert from 'node:assert/strict';
import { CHARACTER_CATALOG } from '../v1.1/modules/catalog.js';
import { getDemoState } from '../v1.1/modules/lab-state.js';
import { characterCardModel } from '../v1.1/modules/character-card.js';

const ready = page => page.waitForFunction(() => document.documentElement.dataset.uiLabReady === 'true');
const bounds = page => page.locator('.workshop').evaluate(node => { const r = node.getBoundingClientRect(); return [r.x + scrollX, r.y + scrollY, r.width, r.height]; });
const top = locator => locator.evaluate(node => node.getBoundingClientRect().top + scrollY);
export async function selectCardCharacter(page, id) {
  await page.locator('.portrait.selected').click();
  await page.locator('#galleryArt').focus(); await page.keyboard.press('Home');
  const index = await page.locator('[data-art]').evaluateAll((nodes, id) => nodes.findIndex(node => node.dataset.art === id), id);
  assert.ok(index >= 0);
  for (let n = 0; n < index; n++) await page.keyboard.press('ArrowRight');
  await page.waitForFunction(id => { const node = document.querySelector('#characterCarousel'); return node.dataset.motion === 'settled' && node.dataset.focusedCharacter === id; }, id);
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#characterCarousel')).height === '0px');
}
export async function reviewCharacterCard(page, { width, checks }) {
  await ready(page);
  if (await page.locator('#characterToggle').getAttribute('aria-expanded') !== 'true') await page.locator('#characterToggle').click();
  const geometry = await bounds(page);
  const card = page.locator('#character');
  assert.equal(await card.locator('.rarity-stars').textContent(), '★★★★★');
  assert.equal(await card.locator('.character-hero').getAttribute('data-rarity'), '5');
  assert.equal(await card.locator('.character-element img').getAttribute('alt'), 'Electro');
  assert.match(await card.locator('.character-element img').getAttribute('src'), /elements\/electro.webp$/);
  assert.equal(await card.locator('.weapon').getAttribute('data-weapon-id'), 'thunderflare-dominion');
  assert.equal(await card.locator('.weapon').getAttribute('data-rarity'), '5');
  assert.equal(await card.locator('.sequence-node').count(), 6);
  assert.equal(await card.locator('.sequence-node[data-state="unavailable"]').count(), 6);
  assert.equal(await card.locator('.sequence-node.is-active').count(), 0, 'Missing investment must not become unlocked');
  assert.equal(await card.locator('.sequence-node img').count(), 6);
  assert.equal(await card.locator('.card-sequence').getAttribute('data-level'), 'unknown');
  const saved = characterCardModel(CHARACTER_CATALOG.find(person => person.id === 'augusta'), getDemoState('augusta'));
  assert.deepEqual(await card.locator('#characterStats tr').evaluateAll(rows => rows.map(row => [...row.children].map(cell => cell.textContent))), saved.stats);
  assert.equal(await card.locator('thead,.comparison-basis,.character-pending,.character-context').count(), 0);
  assert.doesNotMatch(await card.locator('.character-content').innerText(), /Skills MAX|Sequence S0|Simulated build|Build evaluation|Expected|Recommended/);
  const statsTop = await top(card.locator('.stats-heading'));
  await card.locator('#characterSkills summary').focus(); await page.keyboard.press('Space');
  assert.equal(await card.locator('#characterSkills').evaluate(node => node.open), true);
  const body = await card.locator('.card-skills-body').boundingBox();
  assert.ok(await top(card.locator('.stats-heading')) >= statsTop + body.height - 1, 'Skills must push stats down');
  assert.equal(await card.locator('.card-forte-node').count(), 16);
  assert.equal(await card.locator('[data-skill-level]').count(), 5);
  assert.deepEqual(await card.locator('[data-skill-level]').allTextContents(), ['—','—','—','—','—']);
  assert.deepEqual(await bounds(page), geometry, 'Skills changed Workshop geometry');
  await card.locator('#characterSkills summary').click();
  assert.equal(await top(card.locator('.stats-heading')), statsTop, 'Collapsed Skills did not restore stats');
  // No calculated run or loadout selection may replace the saved value column.
  const values = await card.locator('#characterStats').innerText();
  await page.locator('[data-slot="2"]').click(); await chooseIllustrativeResult(page);
  assert.equal(await card.locator('#characterStats').innerText(), values);
  await page.locator('#reset').click();
  await card.locator('#characterSkills summary').click();
  await page.locator('#characterToggle').click();
  assert.equal(await card.locator('.character-content').isVisible(), false);
  await page.locator('#characterToggle').click();
  assert.equal(await card.locator('#characterSkills').evaluate(node => node.open), true, 'Panel toggle lost independent Skills expansion');
  await card.locator('#characterSkills summary').click();
  await selectCardCharacter(page, 'aalto');
  assert.equal(await card.locator('.hero-copy h2').innerText(), 'Aalto');
  assert.equal(await card.locator('.rarity-stars').textContent(), '★★★★');
  assert.equal(await card.locator('.character-hero').getAttribute('data-rarity'), '4');
  assert.equal(await card.locator('.character-element img').getAttribute('alt'), 'Aero');
  assert.equal(await card.locator('.weapon').getAttribute('data-rarity'), 'unknown');
  assert.equal(await card.locator('.weapon img').count(), 0, 'Unknown equipment must not borrow a signature Weapon');
  assert.deepEqual(await card.locator('#characterStats td:last-child').allTextContents(), Array(12).fill('—'));
  await selectCardCharacter(page, 'hsin');
  assert.equal(await card.locator('.character-element img').getAttribute('alt'), 'Electro', 'Card must use canonical identity even when legacy build-stat metadata is unavailable');
  await card.locator('#characterSkills summary').click();
  assert.match(await card.locator('.card-skills-body').innerText(), /Skills unavailable/);
  assert.equal(await card.locator('.card-forte-node').count(), 0);
  await selectCardCharacter(page, 'iuno');
  assert.match(await card.locator('#characterStats').innerText(), /1,940/);
  assert.equal(await card.locator('.character-element img').getAttribute('alt'), 'Aero');
  await selectCardCharacter(page, 'augusta');
  assert.deepEqual(await card.locator('#characterStats tr').evaluateAll(rows => rows.map(row => [...row.children].map(cell => cell.textContent))), saved.stats);
  const collisions = await card.locator('#characterStats tr').evaluateAll(rows => rows.filter(row => { const [a,b] = [...row.cells].map(cell => cell.getBoundingClientRect()); return a.right > b.left + .1 || row.firstElementChild.scrollWidth > row.firstElementChild.clientWidth; }).map(row => row.textContent));
  assert.deepEqual(collisions, []);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width);
  await page.evaluate(() => scrollTo(0, 0));
  checks.push({ label:'Saved Character Card: rarity/element/equipment, explicit unknown investment, read-only Forte, natural Skills flow, single saved stat column, switching and independent panel collapse', width });
}
