import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyProfileModeContextRefresh } from './lib/profile-cohort-mode-context-refresh.mjs';
import { applyProfileWeaponRefresh } from './lib/profile-cohort-weapon-refresh.mjs';
import { applyProfileEchoSonataRefresh } from './lib/profile-cohort-echo-sonata-refresh.mjs';
import { applyProfileStatsErRefresh } from './lib/profile-cohort-stats-er-refresh.mjs';
import { applyProfileSourceRotationRefresh } from './lib/profile-cohort-source-rotation-refresh.mjs';
import { materializeApprovedProfileModes } from './lib/profile-cohort-promotion-materializer.mjs';
import { CHARACTER_CATALOG } from '../src/data/characters.ts';
import { WEAPON_CATALOG } from '../src/data/weapons.ts';
import { ECHO_CATALOG } from '../src/data/echoes.ts';
import { SONATA_CATALOG } from '../src/data/sonatas.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'src/data/profileCohort01GreenLane20260830.ts';

async function loadJson(relativePath) {
  return JSON.parse(await fs.readFile(path.resolve(ROOT, relativePath), 'utf8'));
}

const sourceInput = await loadJson('data/research/profile-source-roster-2026-08-29.json');
const modeRefresh = await loadJson('data/research/profile-cohort-01-mode-context-refresh-2026-08-30.json');
const weaponRefresh = await loadJson('data/research/profile-cohort-01-weapon-refresh-2026-08-30.json');
const echoRefresh = await loadJson('data/research/profile-cohort-01-echo-sonata-refresh-2026-08-30.json');
const statsRefresh = await loadJson('data/research/profile-cohort-01-stats-er-refresh-2026-08-30.json');
const rotationRefresh = await loadJson('data/research/profile-cohort-01-source-rotation-refresh-2026-08-30.json');
const semanticReview = await loadJson('data/research/profile-cohort-01-semantic-promotion-review-2026-08-30.json');

const appliedMode = applyProfileModeContextRefresh(sourceInput, modeRefresh);
const appliedWeapon = applyProfileWeaponRefresh(appliedMode.input, weaponRefresh);
const appliedEcho = applyProfileEchoSonataRefresh(appliedWeapon.input, echoRefresh);
const appliedStats = applyProfileStatsErRefresh(appliedEcho.input, statsRefresh);
const appliedRotation = applyProfileSourceRotationRefresh(appliedStats.input, rotationRefresh);

const materialized = materializeApprovedProfileModes(appliedRotation.input, semanticReview, {
  characters: CHARACTER_CATALOG,
  weapons: WEAPON_CATALOG,
  echoes: ECHO_CATALOG,
  sonatas: SONATA_CATALOG,
});

function json(value) {
  return JSON.stringify(value, null, 2);
}

const content = `// AUTO-GENERATED by scripts/generate-profile-cohort-01-promotion.mjs. Do not hand-edit.\n` +
`// Semantic approval source: data/research/profile-cohort-01-semantic-promotion-review-2026-08-30.json\n` +
`import type { CharacterBuildPreset, EchoLoadoutProfile, RotationProfile, StatTargetProfile, TeamProfile, WeaponRecommendationProfile } from '../profileDomain.ts';\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_META = ${json(materialized.meta)} as const;\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_WEAPONS: readonly WeaponRecommendationProfile[] = ${json(materialized.weaponRecommendations)};\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_ECHOES: readonly EchoLoadoutProfile[] = ${json(materialized.echoLoadouts)};\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_STATS: readonly StatTargetProfile[] = ${json(materialized.statTargets)};\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_TEAMS: readonly TeamProfile[] = ${json(materialized.teams)};\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_ROTATIONS: readonly RotationProfile[] = ${json(materialized.rotations)};\n\n` +
`export const PROFILE_COHORT_01_GREEN_LANE_PRESETS: readonly CharacterBuildPreset[] = ${json(materialized.presets)};\n`;

const outputPath = path.resolve(ROOT, OUTPUT);
await fs.writeFile(outputPath, content, 'utf8');
console.log(`Materialized Cohort 01 promotion: ${materialized.meta.approvedModeCount} modes / ${materialized.meta.approvedCharacterCount} Characters`);
console.log(`Wrote ${OUTPUT}`);
